-- Unified metering: every per-period allowance (free smart reports, free assistant questions,
-- AI menu imports) is counted in one place instead of each feature counting its own history.
-- Additive only; nothing the running code reads is changed.

-- 1. Features learn a daily reset, a default allowance for merchants without a grant, and
--    whether owning the parent feature makes the allowance unlimited.
ALTER TABLE features DROP CONSTRAINT IF EXISTS features_reset_check;
ALTER TABLE features
    ADD CONSTRAINT features_reset_check CHECK (reset_period IN ('NONE', 'DAY', 'WEEK', 'MONTH'));

ALTER TABLE features ADD COLUMN IF NOT EXISTS free_quota INTEGER;
ALTER TABLE features ADD COLUMN IF NOT EXISTS unlimited_with_parent BOOLEAN NOT NULL DEFAULT FALSE;

UPDATE features SET free_quota = 1 WHERE feature_key = 'SMART_REPORT_QUOTA' AND free_quota IS NULL;

INSERT INTO features (feature_key, name, kind, unit, reset_period, parent_key, free_quota, unlimited_with_parent, description)
VALUES
    ('ASSISTANT_QUESTION', 'Günlük asistan sorusu', 'METERED', 'soru', 'DAY', 'SMART_ASSISTANT', 5, TRUE,
     'Akıllı asistanı olmayan paketlerde günde sorulabilecek soru. Akıllı asistan varsa sınırsız.'),
    ('AI_MENU_IMPORT_RUN', 'AI menü aktarımı', 'METERED', 'aktarım', 'MONTH', 'AI_MENU_IMPORT', 0, TRUE,
     'Ayda başlatılabilecek AI menü aktarımı. Pakette ayrıca sınır yoksa AI menü aktarımı olan herkes için sınırsız.')
ON CONFLICT (feature_key) DO NOTHING;

-- 2. Usage per merchant, feature and period ("2026-11-17", "2026-W47", "2026-11", "ALL").
CREATE TABLE IF NOT EXISTS usage_counters (
    merchant_id BIGINT       NOT NULL,
    feature_key VARCHAR(64)  NOT NULL REFERENCES features (feature_key),
    period_key  VARCHAR(16)  NOT NULL,
    used        BIGINT       NOT NULL DEFAULT 0,
    updated_at  TIMESTAMP(6) NOT NULL DEFAULT NOW(),
    PRIMARY KEY (merchant_id, feature_key, period_key),
    CONSTRAINT usage_counters_used_check CHECK (used >= 0)
);

-- 3. Every spend, so a retried request is charged once and a failed job can be given back.
CREATE TABLE IF NOT EXISTS usage_events (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id     BIGINT       NOT NULL,
    feature_key     VARCHAR(64)  NOT NULL REFERENCES features (feature_key),
    period_key      VARCHAR(16)  NOT NULL,
    quantity        INTEGER      NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    reference       VARCHAR(128),
    released_at     TIMESTAMP(6),
    created_at      TIMESTAMP(6) NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_usage_events_idempotency UNIQUE (idempotency_key),
    CONSTRAINT usage_events_quantity_check CHECK (quantity > 0)
);

CREATE INDEX IF NOT EXISTS idx_usage_events_merchant_feature
    ON usage_events (merchant_id, feature_key, created_at);

-- 4. Carry this week's free smart reports over, so nobody gets an extra free report on the switch.
INSERT INTO usage_counters (merchant_id, feature_key, period_key, used)
SELECT merchant_id, 'SMART_REPORT_QUOTA', to_char(date_trunc('week', NOW()), 'IYYY-"W"IW'), count(*)
FROM tbl_smart_report_events
WHERE created_at >= date_trunc('week', NOW())
  AND (credit_source IS NULL OR credit_source = 'FREE')
GROUP BY merchant_id
ON CONFLICT (merchant_id, feature_key, period_key) DO NOTHING;

-- 5. Same for today's answered assistant questions, where that log exists.
DO $$
BEGIN
    IF to_regclass('tbl_assistant_usage_event') IS NOT NULL THEN
        INSERT INTO usage_counters (merchant_id, feature_key, period_key, used)
        SELECT merchant_id, 'ASSISTANT_QUESTION', to_char(NOW(), 'YYYY-MM-DD'), count(*)
        FROM tbl_assistant_usage_event
        WHERE created_at >= date_trunc('day', NOW()) AND outcome = 'ANSWERED'
        GROUP BY merchant_id
        ON CONFLICT (merchant_id, feature_key, period_key) DO NOTHING;
    END IF;
END $$;
