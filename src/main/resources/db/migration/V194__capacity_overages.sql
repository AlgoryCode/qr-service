-- Downgrade over-limit flow. When a merchant holds more branches than the plan now allows, they get
-- 14 days to pick which ones stay active; after that the extra ones become read-only automatically.
-- Additive only.

-- Set while a branch is read-only because it is over the plan's branch limit. Locked branches do not
-- count against the limit and refuse edits; their public menus keep working.
ALTER TABLE tbl_branch ADD COLUMN IF NOT EXISTS capacity_locked_at TIMESTAMP(6);

CREATE TABLE IF NOT EXISTS capacity_overages (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id  BIGINT       NOT NULL,
    feature_key  VARCHAR(64)  NOT NULL REFERENCES features (feature_key),
    limit_value  BIGINT       NOT NULL,
    used_value   BIGINT       NOT NULL,
    detected_at  TIMESTAMP(6) NOT NULL,
    deadline_at  TIMESTAMP(6) NOT NULL,
    resolved_at  TIMESTAMP(6),
    -- MEMBER_CHOICE: the member picked; AUTO: the deadline passed; LIMIT_RAISED: the plan grew again.
    resolution   VARCHAR(16),
    CONSTRAINT capacity_overages_resolution_check
        CHECK (resolution IS NULL OR resolution IN ('MEMBER_CHOICE', 'AUTO', 'LIMIT_RAISED'))
);

-- At most one open overage per merchant and feature.
CREATE UNIQUE INDEX IF NOT EXISTS uq_capacity_overages_open
    ON capacity_overages (merchant_id, feature_key) WHERE resolved_at IS NULL;
