-- Order lines remember how many of their units the guest added from a menu assistant suggestion.
ALTER TABLE tbl_menu_order_item
    ADD COLUMN IF NOT EXISTS assistant_quantity INTEGER NOT NULL DEFAULT 0;

-- One row per question asked to an AI assistant from the dashboard.
CREATE TABLE IF NOT EXISTS tbl_assistant_usage_event (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    merchant_id  BIGINT      NOT NULL,
    branch_id    BIGINT,
    surface      VARCHAR(16) NOT NULL,
    topic        VARCHAR(24) NOT NULL,
    outcome      VARCHAR(16) NOT NULL,
    response_ms  INTEGER,
    created_at   TIMESTAMP(6) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_assistant_usage_merchant_created
    ON tbl_assistant_usage_event (merchant_id, created_at);
