package com.ael.algoryqrservice.fulfillmentservice.application.metering;

import com.ael.algoryqrservice.fulfillmentservice.application.snapshot.EntitlementSnapshotService;
import com.ael.algoryqrservice.fulfillmentservice.application.snapshot.EntitlementSnapshotService.Effective;
import com.ael.algoryqrservice.fulfillmentservice.application.snapshot.EntitlementSnapshotService.Snapshot;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabase;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseBuilder;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseType;
import org.springframework.transaction.support.TransactionTemplate;

import java.util.Map;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.anyLong;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

class MeteringServiceTest {

    private static final long MERCHANT = 7L;

    private EmbeddedDatabase db;
    private JdbcTemplate jdbc;
    private EntitlementSnapshotService snapshots;
    private MeteringService metering;
    private TransactionTemplate tx;

    @BeforeEach
    void setUp() {
        db = new EmbeddedDatabaseBuilder().setType(EmbeddedDatabaseType.H2)
                .setName("metering-" + UUID.randomUUID()).build();
        jdbc = new JdbcTemplate(db);
        jdbc.execute("""
                create table features (feature_key varchar(64) primary key, kind varchar(16) not null,
                  reset_period varchar(16) not null, parent_key varchar(64), free_quota int,
                  unlimited_with_parent boolean not null default false)""");
        jdbc.execute("""
                create table usage_counters (merchant_id bigint not null, feature_key varchar(64) not null,
                  period_key varchar(16) not null, used bigint not null default 0, updated_at timestamp not null,
                  primary key (merchant_id, feature_key, period_key))""");
        jdbc.execute("""
                create table usage_events (id bigint generated by default as identity primary key,
                  merchant_id bigint not null, feature_key varchar(64) not null, period_key varchar(16) not null,
                  quantity int not null, idempotency_key varchar(128) not null unique, reference varchar(128),
                  released_at timestamp, created_at timestamp not null)""");
        jdbc.update("insert into features values ('ASSISTANT_QUESTION', 'METERED', 'DAY', 'SMART_ASSISTANT', 2, true)");
        jdbc.update("insert into features values ('SMART_REPORT_QUOTA', 'METERED', 'WEEK', 'SMART_REPORTING', 1, false)");
        jdbc.update("insert into features values ('QR_BRANCH', 'LIMIT', 'NONE', null, null, false)");
        snapshots = mock(EntitlementSnapshotService.class);
        grant(Map.of());
        DataSourceTransactionManager transactions = new DataSourceTransactionManager(db);
        metering = new MeteringService(jdbc, snapshots, transactions);
        tx = new TransactionTemplate(transactions);
    }

    @AfterEach
    void tearDown() {
        db.shutdown();
    }

    @Test
    void freeQuotaIsSpentThenRefused() {
        assertThat(spend("ASSISTANT_QUESTION", "a").allowed()).isTrue();
        MeteringService.Charge second = spend("ASSISTANT_QUESTION", "b");
        assertThat(second.allowed()).isTrue();
        assertThat(second.usage().remaining()).isZero();

        MeteringService.Charge third = spend("ASSISTANT_QUESTION", "c");
        assertThat(third.allowed()).isFalse();
        assertThat(third.usage().used()).isEqualTo(2);
        assertThat(third.usage().limit()).isEqualTo(2);
        assertThat(jdbc.queryForObject("select count(*) from usage_events", Integer.class)).isEqualTo(2);
    }

    @Test
    void sameKeyIsChargedOnce() {
        spend("ASSISTANT_QUESTION", "a");
        MeteringService.Charge replay = spend("ASSISTANT_QUESTION", "a");

        assertThat(replay.replayed()).isTrue();
        assertThat(replay.usage().used()).isEqualTo(1);
    }

    @Test
    void releaseGivesTheUseBackOnce() {
        spend("SMART_REPORT_QUOTA", "r1");
        assertThat(spend("SMART_REPORT_QUOTA", "r2").allowed()).isFalse();

        assertThat(release("r1")).isTrue();
        assertThat(release("r1")).isFalse();
        assertThat(metering.usage(MERCHANT, "SMART_REPORT_QUOTA").used()).isZero();
        assertThat(spend("SMART_REPORT_QUOTA", "r3").allowed()).isTrue();
    }

    @Test
    void releaseChecksTheOwner() {
        spend("SMART_REPORT_QUOTA", "r1");

        assertThat(release(99L, "r1")).isFalse();
        assertThat(metering.usage(MERCHANT, "SMART_REPORT_QUOTA").used()).isEqualTo(1);
    }

    @Test
    void parentFeatureMakesItUnlimited() {
        grant(Map.of("SMART_ASSISTANT", new Effective("SMART_ASSISTANT", 1, false, 1, null)));

        for (int i = 0; i < 5; i++) {
            assertThat(spend("ASSISTANT_QUESTION", "q" + i).allowed()).isTrue();
        }
        assertThat(metering.usage(MERCHANT, "ASSISTANT_QUESTION").unlimited()).isTrue();
        assertThat(metering.usage(MERCHANT, "ASSISTANT_QUESTION").used()).isEqualTo(5);
    }

    @Test
    void grantSetsTheNumberOverTheFreeQuota() {
        grant(Map.of("SMART_REPORTING", new Effective("SMART_REPORTING", 1, false, 1, null),
                "SMART_REPORT_QUOTA", new Effective("SMART_REPORT_QUOTA", 3, false, 1, null)));

        assertThat(spend("SMART_REPORT_QUOTA", "a").allowed()).isTrue();
        assertThat(spend("SMART_REPORT_QUOTA", "b").allowed()).isTrue();
        assertThat(spend("SMART_REPORT_QUOTA", "c").allowed()).isTrue();
        assertThat(spend("SMART_REPORT_QUOTA", "d").allowed()).isFalse();
    }

    @Test
    void rolledBackRequestGivesItsUseBack() {
        assertThatThrownBy(() -> tx.executeWithoutResult(status -> {
            metering.consume(MERCHANT, "SMART_REPORT_QUOTA", 1, "x", null);
            throw new IllegalStateException("job failed to enqueue");
        })).isInstanceOf(IllegalStateException.class);

        assertThat(metering.usage(MERCHANT, "SMART_REPORT_QUOTA").used()).isZero();
        assertThat(spend("SMART_REPORT_QUOTA", "x").replayed()).isFalse();
    }

    @Test
    void onlyMeteredFeaturesAreMetered() {
        assertThatThrownBy(() -> metering.usage(MERCHANT, "QR_BRANCH")).isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> metering.usage(MERCHANT, "NOPE")).isInstanceOf(IllegalArgumentException.class);
    }

    @Test
    void periodKeys() {
        assertThat(MeteringService.period("DAY").key()).matches("\\d{4}-\\d{2}-\\d{2}");
        assertThat(MeteringService.period("WEEK").key()).matches("\\d{4}-W\\d{2}");
        assertThat(MeteringService.period("MONTH").key()).matches("\\d{4}-\\d{2}");
        assertThat(MeteringService.period("NONE").key()).isEqualTo("ALL");
        assertThat(MeteringService.period("NONE").resetsAt()).isNull();
    }

    private MeteringService.Charge spend(String feature, String key) {
        return tx.execute(status -> metering.consume(MERCHANT, feature, 1, key, null));
    }

    private boolean release(String key) {
        return Boolean.TRUE.equals(tx.execute(status -> metering.release(key)));
    }

    private boolean release(Long merchantId, String key) {
        return Boolean.TRUE.equals(tx.execute(status -> metering.release(merchantId, key)));
    }

    private void grant(Map<String, Effective> features) {
        when(snapshots.read(anyLong())).thenReturn(new Snapshot(1, features));
    }
}
