package com.ael.algoryqrservice.qrservice.branch.capacity;

import com.ael.algoryqrservice.qrservice.exception.BadRequestException;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabase;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseBuilder;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseType;

import java.util.List;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

class CapacityOverageServiceTest {

    private static final long M = 5L;

    private EmbeddedDatabase db;
    private JdbcTemplate jdbc;
    private CapacityOverageService capacity;

    @BeforeEach
    void setUp() {
        db = new EmbeddedDatabaseBuilder().setType(EmbeddedDatabaseType.H2).setName("cap-" + UUID.randomUUID()).build();
        jdbc = new JdbcTemplate(db);
        jdbc.execute("create table merchant_subscriptions (merchant_id bigint primary key, status varchar(32))");
        jdbc.execute("""
                create table merchant_entitlements (merchant_id bigint, feature_key varchar(64), limit_value bigint,
                  unlimited boolean)""");
        jdbc.execute("""
                create table tbl_branch (id bigint primary key, merchant_id bigint, name varchar(64),
                  is_deleted boolean default false, capacity_locked_at timestamp)""");
        jdbc.execute("""
                create table capacity_overages (id bigint generated by default as identity primary key,
                  merchant_id bigint, feature_key varchar(64), limit_value bigint, used_value bigint,
                  detected_at timestamp, deadline_at timestamp, resolved_at timestamp, resolution varchar(16))""");
        jdbc.update("insert into merchant_subscriptions values (?, 'ACTIVE')", M);
        for (long id = 1; id <= 3; id++) {
            jdbc.update("insert into tbl_branch (id, merchant_id, name) values (?, ?, ?)", id, M, "Şube " + id);
        }
        capacity = new CapacityOverageService(jdbc, new DataSourceTransactionManager(db));
    }

    @AfterEach
    void tearDown() {
        db.shutdown();
    }

    @Test
    void downgradeOpensGracePeriodWithoutLockingAnything() {
        limit(1);
        capacity.check(M);

        CapacityOverageService.Status status = capacity.status(M);
        assertThat(status.overLimit()).isTrue();
        assertThat(status.deadline()).isNotNull();
        assertThat(status.active()).isEqualTo(3);
        assertThat(lockedIds()).isEmpty();

        capacity.check(M);
        assertThat(openCount()).isEqualTo(1);
    }

    @Test
    void memberChoiceLocksTheRest() {
        limit(2);
        capacity.check(M);

        CapacityOverageService.Status status = capacity.keep(M, List.of(3L, 1L));

        assertThat(status.overLimit()).isFalse();
        assertThat(lockedIds()).containsExactly(2L);
        assertThat(openCount()).isZero();
    }

    @Test
    void choiceMustFitTheLimit() {
        limit(1);
        capacity.check(M);

        assertThatThrownBy(() -> capacity.keep(M, List.of(1L, 2L))).isInstanceOf(BadRequestException.class);
        assertThatThrownBy(() -> capacity.keep(M, List.of(99L))).isInstanceOf(BadRequestException.class);
    }

    @Test
    void deadlineKeepsTheOldest() {
        limit(1);
        capacity.check(M);
        jdbc.update("update capacity_overages set deadline_at = dateadd('DAY', -1, current_timestamp)");

        capacity.sweep();

        assertThat(lockedIds()).containsExactly(2L, 3L);
        assertThat(jdbc.queryForObject("select resolution from capacity_overages", String.class)).isEqualTo("AUTO");
    }

    @Test
    void raisedLimitUnlocksOldestFirst() {
        limit(1);
        capacity.check(M);
        capacity.keep(M, List.of(1L));
        assertThat(lockedIds()).containsExactly(2L, 3L);

        jdbc.update("update merchant_entitlements set limit_value = 2");
        capacity.entitlementsChanged(M);

        assertThat(lockedIds()).containsExactly(3L);
    }

    @Test
    void planWithoutBranchLineIsLeftAlone() {
        capacity.check(M);
        capacity.sweep();

        assertThat(capacity.status(M).overLimit()).isFalse();
        assertThat(openCount()).isZero();
        assertThat(lockedIds()).isEmpty();
    }

    @Test
    void lapsedPlanIsLeftAlone() {
        limit(1);
        jdbc.update("update merchant_subscriptions set status = 'EXPIRED'");
        capacity.check(M);

        assertThat(openCount()).isZero();
    }

    private void limit(long value) {
        jdbc.update("insert into merchant_entitlements values (?, 'QR_BRANCH', ?, false)", M, value);
    }

    private List<Long> lockedIds() {
        return jdbc.queryForList("select id from tbl_branch where capacity_locked_at is not null order by id", Long.class);
    }

    private int openCount() {
        return jdbc.queryForObject("select count(*) from capacity_overages where resolved_at is null", Integer.class);
    }
}
